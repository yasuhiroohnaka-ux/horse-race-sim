import fs from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();

const BASE_VOLATILITY = {
  "nakayama-turf-1800": {
    courseId: "nakayama-turf-1800",
    upsetScore: 62,
    reason: "中山記念は1番人気の勝率が高すぎず、ヒモ荒れも一定数ある。",
    source: "https://www.jra.go.jp/keiba/thisweek/2026/0301_1/",
  },
  "nakayama-turf-1200": {
    courseId: "nakayama-turf-1200",
    upsetScore: 68,
    reason: "オーシャンSは二桁人気の好走・勝利例があり波乱を含む。",
    source: "https://www.jra.go.jp/keiba/thisweek/2026/0228_1/",
  },
  "hanshin-turf-1600": {
    courseId: "hanshin-turf-1600",
    upsetScore: 75,
    reason: "チューリップ賞は近年高配当決着が見られ、波乱傾向。",
    source: "https://www.jra.go.jp/keiba/thisweek/2026/0301_2/",
  },
};

const POS = ["高配当", "波乱", "穴", "二桁人気", "万馬券"];
const NEG = ["堅い", "順当", "1番人気", "上位人気"];

const clamp = (v, min, max) => Math.max(min, Math.min(max, v));

async function fetchText(url) {
  const res = await fetch(url, {
    headers: {
      "user-agent": "horse-race-sim-bot/1.0",
      accept: "text/html,*/*",
    },
  });
  if (!res.ok) throw new Error(`Fetch failed ${res.status} ${url}`);
  return await res.text();
}

function countHits(text, words) {
  return words.reduce((sum, w) => sum + (text.includes(w) ? 1 : 0), 0);
}

function recalcScore(baseScore, body) {
  const p = countHits(body, POS);
  const n = countHits(body, NEG);
  return Math.round(clamp(baseScore + (p - n) * 2, 35, 85));
}

async function main() {
  const next = {};

  for (const [courseId, item] of Object.entries(BASE_VOLATILITY)) {
    let score = item.upsetScore;
    try {
      const html = await fetchText(item.source);
      score = recalcScore(item.upsetScore, html.slice(0, 12000));
    } catch {
      // Keep base score when fetch fails.
    }
    next[courseId] = { ...item, upsetScore: score };
  }

  const content = `// Auto-generated by scripts/update-race-volatility.mjs
// Do not edit manually.

import type { RaceVolatility } from "./raceVolatility";

export const RACE_VOLATILITY_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};

export const GENERATED_RACE_VOLATILITY: Record<string, RaceVolatility> = ${JSON.stringify(next, null, 2)};
`;

  await fs.writeFile(path.join(ROOT, "lib", "generatedRaceVolatility.ts"), content, "utf8");
  console.log("Updated race volatility.");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});

